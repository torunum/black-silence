// node tools/compile-finisher-reactions.cjs [--check] [game HTML] [output JS]
// Bake the intact close-up poses from the game's actual software rig renderer.
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const {pathToFileURL} = require("node:url");
const {chromium} = require("playwright");
const {PNG} = require("pngjs");

const root = path.resolve(__dirname, "..");
const checkOnly = process.argv.includes("--check");
const args = process.argv.slice(2).filter(arg => arg !== "--check");
const game = path.resolve(args[0] || path.join(root, "THE-BLACK-SILENCE.html"));
const output = path.resolve(args[1] || path.join(root, "src/finisher-reaction-frames.js"));
const modelsFile = path.join(root, "src/finishers.js");
assert.equal(path.basename(output).toLowerCase(), "finisher-reaction-frames.js", "Choose a frame data output");
function resolved(target) {
  return (fs.existsSync(target) ? fs.realpathSync(target) : target).toLowerCase();
}
assert.notEqual(resolved(output), resolved(modelsFile), "Choose a separate output");
assert.notEqual(resolved(output), resolved(game), "Choose a separate output");
const source = fs.readFileSync(modelsFile, "utf8");
const begin = "/* FINISHER_REACTION_MODELS_BEGIN */";
const end = "/* FINISHER_REACTION_MODELS_END */";
assert.equal(source.split(begin).length, 2);
assert.equal(source.split(end).length, 2);
const models = source.slice(source.indexOf(begin) + begin.length, source.indexOf(end));
const gameSource = fs.readFileSync(game, "utf8");
const anchor = "Jk();ju();Yy();X$(J$);D0t();";
assert.equal(gameSource.split(anchor).length, 2);

function exportSheets() {
  const result = {};
  for (const [name, clip] of [["z",groundskeeper],["s",mourner]]) {
    const {w, h} = clip.model.frame;
    const columns = 4;
    const frames = clip.poses.length;
    const image = document.createElement("canvas");
    image.width = w * columns;
    image.height = h * Math.ceil(frames / columns);
    const context = image.getContext("2d");
    for (let i = 0; i < frames; i++) {
      const pixels = X7(clip.model, clip.poses[i], 0, false);
      context.putImageData(new ImageData(pixels.data,w,h), w*(i%columns), h*Math.floor(i/columns));
    }
    result[name] = {w, h, columns, frames, url:image.toDataURL("image/png")};
  }
  return result;
}

(async () => {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "black-silence-finisher-"));
  const fixture = path.join(work, "rig.html");
  let browser;
  try {
    const compiler = `(() => {\n${models}\nwindow.exportFinisherSheets = (${exportSheets.toString()});\n})();\n`;
    fs.writeFileSync(fixture, gameSource.replace(anchor, () => compiler + anchor));
    browser = await chromium.launch({channel:"chrome", headless:true});
    const page = await browser.newPage();
    await page.addInitScript(() => { window.requestAnimationFrame = () => 1; });
    await page.goto(pathToFileURL(fixture).href);
    const sheets = await page.evaluate(() => window.exportFinisherSheets());
    for (const sheet of Object.values(sheets)) {
      const pixels = PNG.sync.read(Buffer.from(sheet.url.split(",")[1], "base64"));
      const png = PNG.sync.write(pixels, {deflateLevel:9, deflateStrategy:0, filterType:0});
      sheet.url = "data:image/png;base64," + png.toString("base64");
    }
    const generated = "// Generated by tools/compile-finisher-reactions.cjs from the native rig poses.\n" +
      "const finisherReactionSheets = " + JSON.stringify(sheets,null,2) + ";\n";
    if (checkOnly) assert.equal(fs.readFileSync(output,"utf8"), generated, "Rebuild the finisher sheets");
    else fs.writeFileSync(output, generated);
    for (const [key, sheet] of Object.entries(sheets))
      console.log(`${key} · ${sheet.frames} frames · ${sheet.w * sheet.columns} × ${sheet.h * Math.ceil(sheet.frames/sheet.columns)} px`);
  } finally {
    if (browser) await browser.close();
    if (fs.existsSync(fixture)) fs.unlinkSync(fixture);
    fs.rmdirSync(work);
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
