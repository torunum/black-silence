// Build compact PCM foley from licensed recordings; no synthesized tones.
// Requires Playwright/Chrome only to decode source MP3/WAV with Web Audio.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { chromium } = require("playwright");
const root = path.resolve(__dirname, "..");
const dir = path.join(root, "assets/audio/reload");
const rate = 32000;
const selections = {
  latch: {
    file: "shotgun/ShotgunSounds/Shell in Chamber.mp3",
    from: 0.684,
    to: 0.795,
    peak: 0.55,
  },
  hinge: {
    file: "shotgun/ShotgunSounds/Rack.mp3",
    from: 0.621,
    to: 0.827,
    peak: 0.53,
  },
  eject: { file: "singlebullet1.wav", from: 0.106, to: 0.252, peak: 0.42 },
  slide: {
    file: "shotgun/ShotgunSounds/First Shell.mp3",
    from: 0.358,
    to: 0.585,
    peak: 0.36,
  },
  seat: {
    file: "shotgun/ShotgunSounds/Subsequent Shells.mp3",
    from: 1.025,
    to: 1.218,
    peak: 0.5,
  },
  close: {
    file: "shotgun/ShotgunSounds/Rack.mp3",
    from: 0.831,
    to: 1.055,
    peak: 0.67,
  },
};
function wave(data) {
  const b = Buffer.alloc(44 + data.length * 2);
  b.write("RIFF");
  b.writeUInt32LE(b.length - 8, 4);
  b.write("WAVEfmt ", 8);
  b.writeUInt32LE(16, 16);
  b.writeUInt16LE(1, 20);
  b.writeUInt16LE(1, 22);
  b.writeUInt32LE(rate, 24);
  b.writeUInt32LE(rate * 2, 28);
  b.writeUInt16LE(2, 32);
  b.writeUInt16LE(16, 34);
  b.write("data", 36);
  b.writeUInt32LE(data.length * 2, 40);
  for (let i = 0; i < data.length; i++)
    b.writeInt16LE(Math.round(data[i] * 32767), 44 + i * 2);
  return b;
}
function processClip(raw, spec) {
  let data = raw.slice(Math.floor(spec.from * rate), Math.ceil(spec.to * rate));
  // Gentle DC/handling-rumble removal and upper-hiss rolloff. Preserve recorded
  // irregular contacts and material texture instead of replacing them with ticks.
  const hp = Math.exp((-2 * Math.PI * 85) / rate),
    lp = 1 - Math.exp((-2 * Math.PI * 7200) / rate);
  let previous = 0,
    high = 0,
    low = 0;
  data = data.map((sample) => {
    high = hp * (high + sample - previous);
    previous = sample;
    low += lp * (high - low);
    return low;
  });
  const peak = Math.max(...data.map(Math.abs));
  let first = data.findIndex((v) => Math.abs(v) > peak * 0.035);
  if (first < 0) throw new Error("Silent recording selection");
  data = data.slice(Math.max(0, first - Math.floor(rate * 0.001)));
  const gain = spec.peak / Math.max(...data.map(Math.abs));
  return data.map(
    (v, i) => v * gain * Math.min(1, i / 24, (data.length - 1 - i) / 384),
  );
}
(async () => {
  fs.mkdirSync(path.join(dir, "processed"), { recursive: true });
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const page = await browser.newPage();
    const decoded = new Map(),
      bank = {},
      provenance = [];
    for (const [name, spec] of Object.entries(selections)) {
      const source = fs.readFileSync(path.join(dir, "source", spec.file));
      if (!decoded.has(spec.file))
        decoded.set(
          spec.file,
          await page.evaluate(async (b64) => {
            const ctx = new OfflineAudioContext(1, 1, 32000);
            const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
            const buffer = await ctx.decodeAudioData(bytes.buffer);
            const mono = new Float32Array(buffer.length);
            for (
              let channel = 0;
              channel < buffer.numberOfChannels;
              channel++
            ) {
              const data = buffer.getChannelData(channel);
              for (let i = 0; i < data.length; i++)
                mono[i] += data[i] / buffer.numberOfChannels;
            }
            return Array.from(mono);
          }, source.toString("base64")),
        );
      const data = processClip(decoded.get(spec.file), spec),
        wav = wave(data);
      fs.writeFileSync(path.join(dir, "processed", name + ".wav"), wav);
      bank[name] = { pcm: wav.subarray(44).toString("base64"), rate };
      provenance.push({
        name,
        ...spec,
        sourceSHA256: crypto.createHash("sha256").update(source).digest("hex"),
        outputSHA256: crypto.createHash("sha256").update(wav).digest("hex"),
        duration: data.length / rate,
        peak: Math.max(...data.map(Math.abs)),
        rms: Math.sqrt(data.reduce((sum, v) => sum + v * v, 0) / data.length),
        dc: data.reduce((sum, v) => sum + v, 0) / data.length,
        clipped: data.filter((v) => Math.abs(v) >= 1).length,
      });
    }
    fs.writeFileSync(
      path.join(root, "src/reload-audio-data.js"),
      "// Generated by tools/compile-reload-audio.cjs from CC0 recorded foley.\n// Sources and processing: docs/audio-sources.json.\nconst BLACK_SILENCE_RELOAD_PCM = " +
        JSON.stringify(bank) +
        ";\n",
    );
    fs.writeFileSync(
      path.join(dir, "processing.json"),
      JSON.stringify(
        {
          sampleRate: rate,
          processing:
            "mono, 85Hz highpass, 7.2kHz lowpass, onset trim, 0.75ms attack / 12ms tail fade, peak scaling, PCM16",
          selections: provenance,
        },
        null,
        2,
      ),
    );
    console.log(
      JSON.stringify(
        provenance.map(({ name, duration, peak, rms, dc, clipped }) => ({
          name,
          duration,
          peak,
          rms,
          dc,
          clipped,
        })),
        null,
        2,
      ),
    );
  } finally {
    await browser.close();
  }
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
